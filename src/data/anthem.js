export const anthemTitle = 'Twenty-Five Winters, One December';
export const anthemDedication = 'for the Class of 2001, REC Calicut';

export const anthemStanzas = [
  `Twenty-five winters have thinned our hair,
gentled our voices, greyed the air —
but somewhere between a merge and a meeting,
a slide deck read, a deadline fleeting,
a corner of us still walks the road
to Chathamangalam. Still owed
a coffee in the mess, a laugh, a fight,
a hostel corridor's forgotten light.`,

  `We came in seven — Arch, Civil, CS,
ECE, EEE, Mech, Prod — no less
than seven rivers to one wide sea,
one campus, one strange family.
We argued codes and cantilevers,
mocked each other's fever dreams and fevers,
borrowed notes we swore we'd give back —
and somehow, together, stayed on track.`,

  `Then life came, quiet as a train,
and scattered us across the plain.
Seattle mornings, Perth blue noons,
Bangalore rains, Dubai monsoons,
Kozhikode kitchens, Delhi flats —
each of us wearing different hats,
each of us thinking, now and again,
I wonder how they're doing, then.`,

  `Well — now you know. They're doing this:
opening a door you didn't miss,
holding a chair with your name on it,
lighting a lamp, a stage, a bit
of Manachira sky in December,
so twenty-five years remember
what twenty-one felt like — the noise,
the crush of friends, the reckless joys.`,

  `Come home. Not to the men and women
you were, but to the ones you're bringing.
Bring your husband, your wife, your child —
let them see the place that filed
the sharp edge off you, gave you a name,
a nickname worse, a lifelong claim
on strangers who are strangers no more —
just batch, just brother, just of yore.`,

  `And when you leave, leave something behind:
a brick, a rupee, a piece of mind
for the Health Centre rising there —
so the next batch, breathing the same air,
finds us not in a photograph
but in a wall, a ward, a laugh
they'll never trace. That's how we stay.
That's twenty-five years earning the day.`,

  `So mark December. Book the flight.
The Gokulam lobby, the Gala night,
the sadhya lunch, the campus walk,
the hug you thought you'd never talk
your way back into — it's all set.
The only piece we haven't met
is you. Come close the circle. Come
be counted. REConverge. Come home.`,
];
